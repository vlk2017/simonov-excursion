#!/usr/bin/env python3
"""Генерирует RIGHTS.md, SOURCES.md и docs/PHOTO_AUDIT.md из data/points.json."""
import json
from pathlib import Path
B = Path(__file__).resolve().parent.parent
d = json.loads((B / "data" / "points.json").read_text(encoding="utf-8"))
T = "Крутицкое подворье"

r = [f"# Права на изображения (экскурсия «{T}»)", "",
     "Все снимки взяты с Викисклада (Wikimedia Commons). Использованы только файлы с пометкой «общественное достояние» или со свободной лицензией (CC BY-SA, CC0). Лицензии и авторы перенесены со страниц файлов; проверьте их по ссылкам. Изображения с водяными знаками и снимки с сайтов с запретом копирования не используются, водяные знаки не убирались.", "",
     "Для лицензий CC BY-SA нужно указывать автора и лицензию. Это сделано под каждым фото на сайте и в таблице ниже. Изображения только уменьшены до размера для телефона (и миниатюры), других изменений нет. Новые снимки пользователя при «рефотосъёмке» остаются у пользователя на телефоне и на сайт не отправляются.", "",
     "| Файл | Что | Год | Автор | Лицензия | Страница на Викискладе | Где используется |", "|---|---|---|---|---|---|---|"]
seen = {}
def add(src, title, year, author, lic, commons, pid):
    if src in seen: seen[src][6].append(pid); return
    seen[src] = [src, title, year, author, lic, commons, [pid]]
for p in d["points"]:
    for ph in p["photos"]:
        add(ph["src"], ph["title"], ph["year"], ph["author"], ph["license"], ph["commons"], p["num"])
        if ph.get("now"):
            n = ph["now"]; add(n["src"], n["note"], n["year"], n["author"], n["license"], n["commons"], p["num"])
    if p.get("heroNow"):
        n = p["heroNow"]; add(n["src"], n["note"], n["year"], n["author"], n["license"], n["commons"], p["num"])
for s in seen.values():
    r.append(f"| `{s[0]}` | {s[1]} | {s[2]} | {s[3]} | {s[4]} | [Викисклад]({s[5]}) | точки {', '.join(str(x) for x in sorted(set(s[6])))} |")
r += ["", f"Всего файлов: {len(seen)}.", "", "## Текст", "", "Тексты рассказов написаны для этой экскурсии по открытым источникам (список в `SOURCES.md`).", "",
      "## Голос", "", "Рассказы озвучены голосом Grigory в HeyGen Voice (как в экскурсии «Ордынка»). Файлы лежат в `audio/heygen/`.", "",
      "## Видео", "", "Видео на сайте нет. См. `docs/VIDEO.md`.", ""]
(B / "RIGHTS.md").write_text("\n".join(r), encoding="utf-8")

s = [f"# Источники (экскурсия «{T}»)", "",
     "Адрес: Москва, Крутицкая улица, 17 (Крутицкое патриаршее подворье). Каждая точка опирается на публичные страницы, ссылки на них есть на самом сайте в блоке «Источники» и ниже. Где источники расходятся, это сказано в рассказе и в строке «Надёжность и оговорки».", "",
     "## Координаты точек", "",
     "Только OpenStreetMap: у каждой точки в `data/points.json` в поле `coordSource` записан номер узла. Значения выгружены через OSM API по рамке района (Overpass API был недоступен).", "",
     "| Точка | Узел OSM | Широта | Долгота | Что это |", "|---|---|---|---|---|"]
for p in d["points"]:
    c = p["coordSource"]
    s.append(f"| {p['num']}. {p['title']} | [{c['node']}]({c['url']}) | {p['lat']} | {p['lon']} | {c['how']} |")
s += ["", "## Источники по точкам", ""]
for p in d["points"]:
    s.append(f"### {p['num']}. {p['title']}")
    for x in p["scene"]["sources"]: s.append(f"- [{x['title']}]({x['url']})")
    s.append(f"- Оговорки: {p['scene']['confidence']}"); s.append("")
s += ["## Расхождения между источниками", "",
      "- **Основание подворья:** 1272 год (сайт подворья) или 1262 год с двумя версиями (Википедия).",
      "- **Строительство и освящение Успенского собора:** 1665 год заложен, 1689 освящён (сайт подворья); 1682 начат, 1699 освящён (Википедия).",
      "- **Службы в нижнем храме собора:** Википедия — возобновились в 1993 году; сайт подворья — 7 ноября 2026 года впервые за 18 лет.",
      "- **Начало реставрации теремка:** 1947 год (Википедия) и 1948 год (сайт подворья).",
      "- **Строительство Митрополичьих палат:** 1655 год или 1655–1670 годы.",
      "- **Изразцы теремка:** число плиток разное у разных источников; архитектор — Ларион Ковалёв (большинство историков), на сайте подворья — Старцев и Ковалёв вместе.", ""]
(B / "SOURCES.md").write_text("\n".join(s), encoding="utf-8")

# PHOTO_AUDIT
a = [f"# Проверка фото экскурсии «{T}» (/krutitsy/), 18 ноября 2026", "",
     "Как проверял: открыл каждый файл и карточку на Викискладе (описание, дата, автор, лицензия), сравнил с текстом точки и с видом на месте по карте OSM. Точек штатива у старых снимков нет, ракурс сопоставлен по кадру.", "",
     "| № | Точка | Первый кадр | Вторая часть кадра | Что на самом деле |", "|---|---|---|---|---|"]
for p in d["points"]:
    ph = p["photos"][0]
    if ph.get("now"):
        first = f"шторка: {ph['src'].split('/')[-1]} ({ph['year']}) и {ph['now']['src'].split('/')[-1]}"
        what = f"Старый снимок: {ph['title']}. Современный: {ph['now']['note']}"
        sec = "пара «тогда — сейчас»"
    else:
        first = f"плашка «Старого снимка нет»: {p['heroNow']['src'].split('/')[-1]}"
        what = p["heroNow"]["note"]
        sec = "старого снимка со свободной лицензией нет"
    a.append(f"| {p['num']} | {p['title']} | {first} | {sec} | {what} |")
a += ["", "## Что не взято и почему", "",
      "- Фото с водяными знаками (Net-Film и т. п.) не использовались, водяные знаки не убирались.",
      "- Снимок «Крутицкие казармы» 1913 года (Городской альбом) не подходит как пара к башне и приказным палатам: ракурс другой. Он стоит в карусели точки 8 как старый вид казарм.",
      "- Снимок надгробий 1900 года подписан на Викискладе «в Крутицком соборе», где именно снято, неизвестно. Он в карусели точки 4 без привязки к конкретному зданию.",
      "- Для точек 1, 4, 5, 6, 8 свободных старых снимков нужного вида не найдено, там первый кадр — современное фото с плашкой.", ""]
(B / "docs" / "PHOTO_AUDIT.md").write_text("\n".join(a), encoding="utf-8")
print("docs ok")
