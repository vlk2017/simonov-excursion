#!/usr/bin/env python3
"""Генерирует RIGHTS.md и SOURCES.md из data/points.json (чтобы права и источники не расходились с данными)."""
import json
from pathlib import Path
B = Path(__file__).resolve().parent.parent
d = json.loads((B / "data" / "points.json").read_text(encoding="utf-8"))

r = ["# Права на изображения (экскурсия «Скорбященский храм на Ордынке»)", "",
     "Все снимки взяты с Викисклада (Wikimedia Commons). Использованы только файлы с пометкой «общественное достояние» или со свободной лицензией. Лицензии и авторы перенесены со страниц файлов; проверьте их по ссылкам. Изображения с водяными знаками и снимки с сайтов с запретом копирования не используются.", "",
     "Для лицензий CC BY-SA и Free Art License нужно указывать автора и лицензию. Это сделано под каждым фото на сайте и в таблице ниже. Изображения только уменьшены до размера для телефона (и миниатюры), других изменений нет. Производные работы (новые снимки пользователя при «рефотосъёмке») остаются у пользователя на телефоне и на сайт не отправляются.", "",
     "| Файл | Что | Год | Автор | Лицензия | Страница на Викискладе | Где используется |", "|---|---|---|---|---|---|---|"]
seen = {}
def add(src, title, year, author, lic, commons, pid):
    if src in seen:
        seen[src][6].append(pid); return
    seen[src] = [src, title, year, author, lic, commons, [pid]]
for p in d["points"]:
    for ph in p["photos"]:
        add(ph["src"], ph["title"], ph["year"], ph["author"], ph["license"], ph["commons"], p["num"])
        if ph.get("now"):
            n = ph["now"]; add(n["src"], n["note"], n["year"], n["author"], n["license"], n["commons"], p["num"])
    if p.get("nowContext"):
        n = p["nowContext"]; add(n["src"], n["note"], n["year"], n["author"], n["license"], n["commons"], p["num"])
for s in seen.values():
    r.append(f"| `{s[0]}` | {s[1]} | {s[2]} | {s[3]} | {s[4]} | [Викисклад]({s[5]}) | точки {', '.join(str(x) for x in sorted(set(s[6])))} |")
r += ["", f"Всего файлов: {len(seen)}.", "", "## Текст", "",
      "Тексты рассказов написаны для этой экскурсии по открытым источникам (список в `SOURCES.md`).", "",
      "## Видео", "", "Видео на сайте нет. См. `docs/VIDEO.md`.", ""]
(B / "RIGHTS.md").write_text("\n".join(r), encoding="utf-8")

s = ["# Источники (экскурсия «Скорбященский храм на Ордынке»)", "",
     "Адрес: Москва, Большая Ордынка, 20. Каждая точка опирается на публичные страницы, ссылки на них есть на самом сайте в блоке «Источники» и ниже. Где источники расходятся, это сказано в рассказе и в строке «Надёжность и оговорки».", "",
     "## Координаты точек", "",
     "Только OpenStreetMap: у каждой точки в `data/points.json` в поле `coordSource` записан номер узла. Значения взяты из Nominatim (отношение R6897502) и выгрузки OSM API по рамке района. Overpass API на момент работы не отвечал.", "",
     "| Точка | Узел OSM | Широта | Долгота | Что это |", "|---|---|---|---|---|"]
for p in d["points"]:
    c = p["coordSource"]
    s.append(f"| {p['num']}. {p['title']} | [{c['node']}]({c['url']}) | {p['lat']} | {p['lon']} | {c['how']} |")
s += ["", "## Источники по точкам", ""]
for p in d["points"]:
    s.append(f"### {p['num']}. {p['title']}")
    for x in p["scene"]["sources"]:
        s.append(f"- [{x['title']}]({x['url']})")
    s.append(f"- Оговорки: {p['scene']['confidence']}")
    s.append("")
s += ["## Расхождения между источниками", "",
      "- **Закрытие храма:** 1930 (Соборы.ру), 1932 (приходской сайт), 1933 (Википедия). Храм закрыли в начале 1930-х и открыли в 1948 году. Он НЕ работал всё советское время.",
      "- **Даты строительства ротонды:** 1823–1836 (Википедия), 1831–1836 (сайт РПЦ). Освящение 20 сентября 1836 года подтверждено словом митрополита Филарета (azbyka.org).",
      "- **Баженов и усадьба Долгова:** авторство Баженова для главного дома не подтверждено исследователями.",
      "- **Икона «с грошиками»:** это петербургский список, а не икона с Ордынки.", ""]
(B / "SOURCES.md").write_text("\n".join(s), encoding="utf-8")
print("docs ok")
