def photo(base, nowobj=None, **kw):
    d = dict(base)
    d.update(kw)
    d.pop("remote_name", None)
    if "lic" in d: d["license"] = d.pop("lic")
    if "commons_file" in d: d["commons"] = C(d.pop("commons_file"))
    d.setdefault("remote", None)
    d.setdefault("viewpoint", None)
    if "src" in d and not d["src"].startswith("img/"): d["src"] = "img/then/" + d["src"]
    if nowobj: d["now"] = nowobj
    return d

