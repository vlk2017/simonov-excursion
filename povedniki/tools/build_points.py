def lic_short(r): return r["licence"] if r["status"] == "free" else "без свободной лицензии, с указанием источника"

def P(pid, focal=None, stand=None):
    """Слайд-снимок из реестра (старый или современный без пары)."""
    r = BY[pid]
    rights = r["licence"] + ("" if r["watermark"].startswith("нет") else " " + r["watermark"] + ".")
    d = {"src": "img/" + r["file"], "title": r["title"], "year": r["year"], "author": r["author"], "license": lic_short(r), "rights": rights,
         "stand": stand or r["stand"], "commons": r["card"], "sourceName": r["source_name"], "archive": r["collection"], "original": r["original"],
         "confidence": r["confidence"], "kind": r["kind"], "remote": None, "viewpoint": None}
    if r["kind"] != "archival": d["modern"] = True
    if "PastVu" in r["watermark"]: d["wm"] = True
    if focal: d["focal"] = focal
    return d

def now_of(pid, focal=None):
    r = BY[pid]
    d = {"src": "img/" + r["file"], "remote": None, "year": r["year"], "author": r["author"], "license": lic_short(r), "note": r["title"] + ". " + r["stand"],
         "commons": r["card"], "sourceName": r["source_name"], "archive": r["collection"]}
    if focal: d["focal"] = focal
    return d

def pair(old_id, now_id, note, focal_old=None, focal_now=None):
    d = P(old_id, focal_old)
    d["now"] = now_of(now_id, focal_now)
    d["stand"] = d["stand"] + " " + note
    return d

def heroOf(pid, missing, focal=None):
    n = now_of(pid, focal); n["missingThen"] = missing
    return n

