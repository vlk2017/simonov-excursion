#!/usr/bin/env python3
"""Генерирует RIGHTS.md, SOURCES.md и docs/PHOTO_AUDIT.md из data/points.json."""
import json
from pathlib import Path
B = Path(__file__).resolve().parent.parent
d = json.loads((B / "data" / "points.json").read_text(encoding="utf-8"))
T = "Храм исповедников в Поведниках"

r = [f"# Права на изображения (экскурсия «{T}»)", "",
     "Все снимки взяты с Викисклада (Wikimedia Commons). Использованы только файлы с пометкой «общественное достояние» или со свободной лицензией (CC BY, CC BY-SA, CC0). Лицензии и авторы перенесены со страниц файлов; проверьте их по ссылкам. Изображения с водяными знаками и снимки с сайтов с запретом копирования не используются, водяные знаки не убирались.", "",
     "Для лицензий CC BY-SA нужно указывать автора и лицензию. Это сделано под каждым фото на сайте и в таблице ниже. Изображения только уменьшены до размера для телефона (и миниатюры), других изменений нет. Новые снимки пользователя при «рефотосъёмке» остаются у пользователя на телефоне и на сайт не отправляются.", "",
     "| Файл | Что | Год | Автор | Лицензия | Страница на Викискладе | Где используется |", "|---|---|---|---|---|---|---|"]
seen = {}
def add(src, title, year, author, lic, commons, pid):
    if src in seen: seen[src][6].append(pid); return
    seen[src] = [src, title, year, author, lic, commons, [pid]]
for p in d["points"]:
    for ph in p["photos"]:
        add(ph["src"], ph["title"], ph["year"], ph["author"], ph["license"], ph["commons"], p["num"])
        if ph.get("now"):
            n = ph["now"]; add(n["src"], n["note"], n["year"], n["author"], n["license"], n["commons"], p["num"])
    if p.get("heroNow"):
        n = p["heroNow"]; add(n["src"], n["note"], n["year"], n["author"], n["license"], n["commons"], p["num"])
for s in seen.values():
    r.append(f"| `{s[0]}` | {s[1]} | {s[2]} | {s[3]} | {s[4]} | [Викисклад]({s[5]}) | точки {', '.join(str(x) for x in sorted(set(s[6])))} |")
r += ["", f"Всего файлов: {len(seen)}.", "", "## Текст", "", "Тексты рассказов написаны для этой экскурсии по открытым источникам (список в `SOURCES.md`).", "",
      "## Голос", "", "Рассказы озвучены голосом Grigory в HeyGen Voice (как в экскурсиях «Ордынка» и «Крутицы»). Файлы лежат в `audio/heygen/`.", "",
      "## Видео", "", "Видео на сайте нет. См. `docs/VIDEO.md`.", ""]
(B / "RIGHTS.md").write_text("\n".join(r), encoding="utf-8")

s = [f"# Источники (экскурсия «{T}»)", "",
     "Адрес: Московская область, городской округ Мытищи, посёлок Поведники, Соборная площадь, 1. Каждая точка опирается на публичные страницы, ссылки на них есть на самом сайте в блоке «Источники» и ниже. Где источники расходятся, это сказано в рассказе и в строке «Надёжность и оговорки».", "",
     "## Координаты точек", "",
     "Только OpenStreetMap: у каждой точки в `data/points.json` в поле `coordSource` записан номер узла. Значения выгружены через OSM API по рамке района (Overpass API был недоступен).", "",
     "| Точка | Узел OSM | Широта | Долгота | Что это |", "|---|---|---|---|---|"]
for p in d["points"]:
    c = p["coordSource"]
    s.append(f"| {p['num']}. {p['title']} | [{c['node']}]({c['url']}) | {p['lat']} | {p['lon']} | {c['how']} |")
s += ["", "## Источники по точкам", ""]
for p in d["points"]:
    s.append(f"### {p['num']}. {p['title']}")
    for x in p["scene"]["sources"]: s.append(f"- [{x['title']}]({x['url']})")
    s.append(f"- Оговорки: {p['scene']['confidence']}"); s.append("")
s += ["## Расхождения между источниками", "",
      "- **Происхождение названия:** сайт храма — рассказ старожилов (холера 1893 года, заповедное место); Википедия — заповедное имение Рябушинских после закона 1899 года (в Википедии у этого утверждения нет источника).",
      "- **Основание посёлка:** Википедия — 1965 год; сайт храма — зона отдыха с 1961 года, без названия до 1995 года.",
      "- **Заключённые на канале:** сайт храма — 1,2 миллиона человек; Википедия — до 200 тысяч, большая цифра не подтверждена.",
      "- **Начало стройки храма:** Regions.ru — лето 2013 года; каталог «Храмы России» — 2014 год. Службы в новом здании: «Храмы России» — с 2024 года.",
      "- **Название храма:** «Новомучеников и исповедников Церкви Русской» (сайт храма, Regions.ru) и «Новомучеников и исповедников Российских» (сайт епархии, карточка Московской епархии). Это один праздник, Собор новомучеников.",
      "- **Освящение нового храма:** даты в открытых источниках не нашли.",
      "- **Часовня в Деденеве:** на сайте Sobory.ru — год постройки «между 2007 и 2008», а освящение 22 июня 2009 года (там же и в «Вечернем Дмитрове»). В рассказе названа дата освящения.", "",
      "## Источники только по http (не включены в список на сайте)", "",
      "Эти страницы не открываются по https, поэтому на сайте они не указаны, но использованы при проверке:", "",
      "- Каталог «Храмы России» (temples.ru), карточка храма-часовни Новомучеников и исповедников Российских в Поведниках: даты стройки 2014 и 2024.",
      "- «Православная Москва» (orthodoxmoscow.ru): архив Дмитлага уничтожен в 1941 году.", "",
      "## Не использовано", "",
      "- Священник Канардов (Троицкое): источники расходятся в фамилии, годе рождения и в том, о каком Троицком идёт речь. Связь с Поведниками подтвердить нельзя.",
      "- Сайт Мытищинского благочиния (mitishi-blagoch.ru): отдаёт ошибку 403.", ""]
(B / "SOURCES.md").write_text("\n".join(s), encoding="utf-8")

# PHOTO_AUDIT
a = [f"# Проверка фото экскурсии «{T}» (/povedniki/), 18 ноября 2026", "",
     "Как проверял: открыл каждый файл и карточку на Викискладе (описание, дата, автор, лицензия), сравнил с текстом точки и с видом на месте по карте OSM. Точек штатива у старых снимков нет, ракурс сопоставлен по кадру.", "",
     "| № | Точка | Первый кадр | Вторая часть кадра | Что на самом деле |", "|---|---|---|---|---|"]
for p in d["points"]:
    ph = p["photos"][0]
    if ph.get("now"):
        first = f"шторка: {ph['src'].split('/')[-1]} ({ph['year']}) и {ph['now']['src'].split('/')[-1]}"
        what = f"Старый снимок: {ph['title']}. Современный: {ph['now']['note']}"
        sec = "пара «тогда — сейчас»"
    else:
        first = f"плашка «Старого снимка нет»: {p['heroNow']['src'].split('/')[-1]}"
        what = p["heroNow"]["note"]
        sec = "старого снимка со свободной лицензией нет"
    a.append(f"| {p['num']} | {p['title']} | {first} | {sec} | {what} |")
a += ["", "## Что не взято и почему", "",
      "- Фото с водяными знаками не использовались, водяные знаки не убирались.",
      "- На Викискладе всего два свободных снимка самих Поведников: храм (2021) и вид сверху (2024). Они использованы на точках 1, 7 и 8 с разной обрезкой.",
      "- Снимки Троицкого (точка 2) и Чиверёва (точка 6) — это соседние места, а не Поведники. Подписи на сайте это говорят прямо.",
      "- Снимки пансионата и аллеи (точки 3 и 4) подписаны на Викискладе только «Мытищинский район». Привязка к пансионату «Клязьма» — по координатам снимка, подпись на сайте это оговаривает.",
      "- Снимок заключённых на стройке канала (точка 5) — общий, место съёмки неизвестно. Он стоит в карусели как старый снимок без пары, не как «тогда — сейчас».",
      "- Пар «тогда — сейчас» нет: старых свободных снимков именно этих мест не нашли. У всех восьми точек первый кадр — современное фото с плашкой «Старого снимка нет».", ""]
(B / "docs" / "PHOTO_AUDIT.md").write_text("\n".join(a), encoding="utf-8")
print("docs ok")
